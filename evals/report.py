#!/usr/bin/env python3
"""Write docs/evals/report.md from an evaluation run folder.

Combines the runner's deterministic checks (results.jsonl, run.json) with the Foundry judge results
(foundry-output-items.json, foundry-run.json) when present. Standard library only.
Usage: python3 evals/report.py <run folder> [--out docs/evals/report.md]
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
from collections import Counter
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
CHECKS = {
    "tool_selection": "Tool selection",
    "numeric_accuracy": "Numeric accuracy",
    "grounded_numbers": "Numbers from tools",
    "decision": "Decision rules",
}
JUDGES = {
    "task_adherence": "Task adherence",
    "tool_call_accuracy": "Tool-call accuracy",
    "intent_resolution": "Intent resolution",
    "groundedness": "Groundedness",
}
MARK = {"pass": "✓", "fail": "✗", "n/a": "–", None: "–"}


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def judge_marks(item: dict | None) -> dict[str, tuple[str, dict]]:
    marks = {}
    for r in (item or {}).get("results", []):
        if r.get("name") in JUDGES:
            status = "skipped" if r.get("status") == "skipped" or r.get("passed") is None else ("pass" if r["passed"] else "fail")
            marks[r["name"]] = (status, r)
    return marks


def expected_refusal(row: dict) -> bool:
    """A call the tools refused (scope, role, workflow or guardrail) or the user declined, in a case whose
    deterministic checks all pass: the agent behaved as designed."""
    declined = row["checks"]["decision"].get("expected") == "nothing logged" and any(c["name"] == "log_decision" for c in row["tool_calls"])
    refused = any(c["outcome"] != "ok" for c in row["tool_calls"])
    return row["result"] == "pass" and (refused or declined)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("run_folder")
    parser.add_argument("--out", default=str(REPO / "docs" / "evals" / "report.md"))
    args = parser.parse_args()
    folder = Path(args.run_folder).resolve()
    rows = [json.loads(line) for line in (folder / "results.jsonl").read_text(encoding="utf-8").splitlines() if line.strip()]
    run = json.loads((folder / "run.json").read_text(encoding="utf-8"))
    items_path, foundry_path = folder / "foundry-output-items.json", folder / "foundry-run.json"
    items = {i["datasource_item"]["case_id"]: i for i in json.loads(items_path.read_text())["data"]} if items_path.exists() else {}
    foundry = json.loads(foundry_path.read_text()) if foundry_path.exists() else None
    created = run["created_utc"][:10]

    lines = [
        "---",
        "title: Agent evaluation report",
        "description: Results of the Cost-to-Serve agent evaluation run, with deterministic checks and Foundry judge scores. Generated by evals/report.py.",
        f"ms.date: {created}",
        "---",
        "",
        "## Summary",
        "",
        "Generated by `evals/report.py` from one run of `./scripts/run-evals.sh`. Data is illustrative.",
        "",
        "| Item | Value |",
        "|---|---|",
        f"| Run | `{run['run_id']}` on {created} |",
        f"| Agent model | `{run['model']}` (same instructions and tools as the studio) |",
        f"| Seed data | version `{run['seed_version']}` |",
        f"| Dataset | `evals/dataset.jsonl`, {run['cases']} cases, SHA-256 `{run['dataset_sha256'][:12]}` |",
        f"| Tokens (agent turns) | {run['input_tokens']:,} input, {run['output_tokens']:,} output |",
        f"| Foundry evaluation | {('`' + foundry['name'] + '` in project `proj-evals`, judge `' + foundry['model'] + '`, status ' + foundry['status']) if foundry else 'not run (--skip-foundry)'} |",
        "",
        "### Deterministic checks (runner, no model)",
        "",
        "| Check | What it verifies | Passed | Failed | Not applicable |",
        "|---|---|---|---|---|",
    ]
    meaning = {
        "tool_selection": "The agent called the expected tools with the expected arguments",
        "numeric_accuracy": "The answer quotes the engine's numbers, and none it must not show",
        "grounded_numbers": "Every number quoted appears in a tool result, the question or the instructions",
        "decision": "Decisions are logged only when expected, with the right action, region and setting",
    }
    for key, label in CHECKS.items():
        c = Counter(r["checks"][key]["result"] for r in rows)
        lines.append(f"| {label} | {meaning[key]} | {c['pass']} | {c['fail']} | {c['n/a']} |")
    passed = sum(r["result"] == "pass" for r in rows)
    lines += ["", f"**{passed} of {len(rows)} cases pass every applicable deterministic check.**", ""]

    if items:
        lines += [
            "### Foundry judges (LLM-graded)",
            "",
            "| Evaluator | Passed | Failed | Skipped |",
            "|---|---|---|---|",
        ]
        for key, label in JUDGES.items():
            c = Counter(judge_marks(items.get(r["id"])).get(key, ("skipped", {}))[0] for r in rows)
            lines.append(f"| {label} | {c['pass']} | {c['fail']} | {c['skipped']} |")
        refusals = [r["id"] for r in rows
                    if judge_marks(items.get(r["id"])).get("tool_call_accuracy", ("", {}))[0] == "fail" and expected_refusal(r)]
        if refusals:
            lines += ["", f"Expected refusals: {len(refusals)} tool-call accuracy failures are decisions that the tools refused or "
                          "the user declined by design (marked † below): Luis asking for another region, a role that may not take the step, the "
                          "guardrail, or a declined confirmation. The agent behaved correctly; the judge scores the refused call down."]
        lines.append("")

    lines += ["### By persona", "", "| Persona | Cases | All deterministic checks pass | All judges pass |", "|---|---|---|---|"]
    for persona in sorted({r["persona"] for r in rows}):
        group = [r for r in rows if r["persona"] == persona]
        judged = [r for r in group if r["id"] in items]
        all_judges = sum(all(m[0] != "fail" for m in judge_marks(items[r["id"]]).values()) for r in judged)
        lines.append(f"| {persona.capitalize()} | {len(group)} | {sum(r['result'] == 'pass' for r in group)} | "
                     f"{all_judges if judged else '–'} |")

    lines += [
        "",
        "## Results by case",
        "",
        "Checks: tools, numbers, grounded numbers, decision. Judges: task adherence, tool-call accuracy, intent resolution, groundedness. "
        "✓ pass, ✗ fail, – not applicable or skipped.",
        "",
        "| Case | Persona | Tools called | Numbers matched | Checks | Judges |",
        "|---|---|---|---|---|---|",
    ]
    for r in rows:
        checks = " ".join(MARK[r["checks"][k]["result"]] for k in CHECKS)
        marks = judge_marks(items.get(r["id"]))
        judges = " ".join({"pass": "✓", "fail": "✗"}.get(marks.get(k, ("skipped",))[0], "–") for k in JUDGES) if items else "not run"
        if marks.get("tool_call_accuracy", ("",))[0] == "fail" and expected_refusal(r):
            judges += " †"
        calls = ", ".join(f"{c['name']}{'' if c['outcome'] == 'ok' else ' (' + c['outcome'] + ')'}" for c in r["tool_calls"]) or "none"
        n = r["checks"]["numeric_accuracy"]
        numbers = f"{n['matched']}/{n['expected_count']}" if n["result"] != "n/a" and "matched" in n else "–"
        lines.append(f"| `{r['id']}` | {r['persona'].capitalize()} | {cell(calls)} | {numbers} | {checks} | {judges} |")

    findings = []
    for r in rows:
        notes = []
        for key, label in CHECKS.items():
            c = r["checks"][key]
            if c["result"] != "fail":
                continue
            detail = {
                "tool_selection": lambda: "missing " + "; ".join(c.get("missing", [])) + (" forbidden " + ", ".join(c["forbidden_called"]) if c.get("forbidden_called") else ""),
                "numeric_accuracy": lambda: "not quoted: " + ", ".join(f"{e['field']}={e['value']}" for e in c["expected"] if not e["quoted"])
                    + ("; leaked: " + ", ".join(e["quoted"] for e in c["must_not_appear_but_did"]) if c["must_not_appear_but_did"] else ""),
                "grounded_numbers": lambda: "not from a tool: " + ", ".join(c["unsupported"]),
                "decision": lambda: f"expected {c.get('expected')}, logged {json.dumps(c.get('logged'))}",
            }[key]()
            notes.append(f"{label}: {detail}")
        for key, (status, result) in judge_marks(items.get(r["id"])).items():
            if status == "fail":
                prefix = "† expected refusal. " if key == "tool_call_accuracy" and expected_refusal(r) else ""
                reason = (result.get("reason") or "").strip()
                notes.append(f"{JUDGES[key]} (score {result.get('score')}): {prefix}{reason[:280]}{'…' if len(reason) > 280 else ''}")
        if notes:
            findings.append((r, notes))

    lines += ["", "## Findings", ""]
    if not findings:
        lines.append("No failures.")
    for r, notes in findings:
        lines += [f"### `{r['id']}` ({r['persona'].capitalize()})", "", f"Question: {r['query']}", ""]
        lines += [f"* {cell(n)}" for n in notes]
        lines.append("")

    lines += [
        "## How the run works",
        "",
        "* The runner (`evals/CostToServe.Evals`) asks each question as Dana or Luis through the studio's own agent code: the same "
        "instructions, the same seven tools with the same scope rules, and the same model deployment. Each case starts from its own "
        "in-memory decision log, so cases never affect each other or the demo.",
        "* Expected numbers are not typed by hand. The runner calls the same tools directly before the question is asked and reads "
        "the fields listed in the dataset, so the expectations follow the engine and the seed data.",
        "* A quoted number matches when it equals the engine's value at the precision written (one unit of the last digit), so "
        "28,186,400 matches \"$28.2M\".",
        "* The Foundry step submits each turn (system prompt, question, tool calls, tool results and answer, plus tool definitions) "
        "to the isolated `proj-evals` project, which has no connections. The deterministic results are carried along as string "
        "checks so all scores appear in the Foundry portal.",
        "",
        f"Generated {dt.datetime.now(dt.timezone.utc):%Y-%m-%d %H:%M} UTC.",
        "",
    ]
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
